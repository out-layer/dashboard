// One-shot generator: per-route layout.tsx files carrying page metadata
// (titles <= 60 chars with the " · OutLayer" template, descriptions ~120-158),
// derived for docs from lib/docs-nav.mjs labels + scripts/llms-manifest.mjs
// summaries. Safe to re-run: overwrites only files it owns (marker comment).
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DOCS_NAV } from '../lib/docs-nav.mjs'
import { SECTIONS } from './llms-manifest.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MARKER = '// @generated by scripts/gen-seo-layouts.mjs — edit the generator, not this file.'

const summaries = new Map(
  SECTIONS.flatMap((s) => s.pages).flatMap((p) => (p.path ? [[p.path, p.summary]] : [])),
)

const trim = (s, n = 158) => (s.length <= n ? s : s.slice(0, n - 1).replace(/[,;: ]+\S*$/, '') + '…')

const APP_PAGES = [
  ['app/playground', 'Playground', 'Run WASI code from a GitHub repo inside an Intel TDX enclave and get an attested result — straight from the browser, no setup.'],
  ['app/projects', 'Projects', 'Create OutLayer projects, manage versions and per-project secrets, and keep persistent storage across code updates.'],
  ['app/executions', 'Executions', 'Every compilation and execution job with status, cost and TEE attestation — open any job to verify what exactly ran.'],
  ['app/secrets', 'Secrets', 'Encrypted secrets only your code inside the enclave can read: create them, bind to projects and control access conditions.'],
  ['app/wallet/manage', 'Wallets', 'Policy-guarded agent wallets: freeze or unfreeze keys, manage policies and browser-saved API keys for wallets you control.', true],
  ['app/wallet/approvals', 'Approvals', 'Multisig requests for your agent wallets: review the exact operation and the hash your NEP-413 signature commits to.', true],
  ['app/wallet/audit', 'Audit log', 'Full history of every operation your agent wallets performed, with statuses and timestamps.', true],
  ['app/vault', 'Vaults', 'Deploy a sovereign MPC vault bound to your NEAR account and keep custody of secrets and wallets under your own contract.'],
  ['app/payment-keys', 'Payment keys', 'Prepaid USDC keys for the HTTPS API: create keys, top up balances and control spending limits.'],
  ['app/earnings', 'Earnings', 'What your projects earned from on-chain and HTTPS calls, with balances and withdrawals in one place.'],
  ['app/workers', 'Workers', 'The live TEE fleet executing OutLayer jobs — every worker&apos;s Intel TDX attestation is independently verifiable.'.replace('&apos;', "'")],
  ['app/stats', 'Stats', 'Platform-wide metrics: executions, success rate, custody activity and live pricing limits, refreshed every 30 seconds.'],
  ['app/settings', 'Settings', 'Your account, network selection and API keys.'],
  ['app/attestation', 'Execution attestation', 'Cryptographic proof of an OutLayer execution: enclave signature, TDX measurements and the inputs and outputs of the job.'],
]

// Utility pages that carry secrets in the URL: keep them out of indexes.
const NOINDEX_PAGES = [
  ['app/wallet', 'Wallet handoff'],
  ['app/wallet/fund', 'Fund wallet'],
]

function layoutSource({ title, description, robots, retemplate }) {
  // An intermediate layout that sets a plain-string title swallows the root
  // title.template for its children — segments with child routes re-declare it.
  const meta = [
    retemplate
      ? `  title: { default: ${JSON.stringify(title)}, template: '%s · OutLayer' },`
      : `  title: ${JSON.stringify(title)},`,
  ]
  if (description) meta.push(`  description: ${JSON.stringify(description)},`)
  if (robots === 'noindex') meta.push(`  robots: { index: false, follow: false },`)
  if (robots === 'index') meta.push(`  robots: { index: true, follow: true },`)
  return `${MARKER}
import type { Metadata } from 'next';

export const metadata: Metadata = {
${meta.join('\n')}
};

export default function Layout({ children }: { children: React.ReactNode }) {
  return children;
}
`
}

let written = 0
function emit(dir, data) {
  const file = resolve(root, dir, 'layout.tsx')
  if (existsSync(file) && !readFileSync(file, 'utf8').startsWith(MARKER)) {
    console.warn(`skip (hand-written): ${dir}/layout.tsx`)
    return
  }
  mkdirSync(resolve(root, dir), { recursive: true })
  writeFileSync(file, layoutSource(data))
  written++
}

for (const [dir, title, description, reindex] of APP_PAGES) {
  emit(dir, { title, description, robots: reindex ? 'index' : undefined })
}
for (const [dir, title] of NOINDEX_PAGES) {
  emit(dir, { title, robots: 'noindex', retemplate: dir === 'app/wallet' })
}
// app/attestation wraps the dynamic [jobId] segment the same way.
emit('app/attestation', {
  title: 'Execution attestation',
  description: 'Cryptographic proof of an OutLayer execution: enclave signature, TDX measurements and the inputs and outputs of the job.',
  retemplate: true,
})
for (const page of DOCS_NAV.flatMap((g) => g.pages)) {
  const dir = 'app' + page.href
  const description = summaries.has(page.href) ? trim(summaries.get(page.href)) : undefined
  emit(dir, { title: page.label, description })
}

console.log(`wrote ${written} layout.tsx files`)
